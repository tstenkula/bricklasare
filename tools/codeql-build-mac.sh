#!/bin/bash
set -euo pipefail

if [ "${1:-}" = "--diagnostics" ]; then
  # Keep failed extraction useful without uploading the database or environment.
  python3 - <<'PY'
import os
from pathlib import Path
import re

database = os.environ.get("CODEQL_EXTRACTOR_SWIFT_WIP_DATABASE")
if not database:
    print("Swift extractor diagnostics are unavailable: no database path was set.")
    raise SystemExit(0)
root = Path(database)
remaining = 24000
paths = sorted((root / "diagnostic").rglob("*.json*"))[:40]
paths += sorted((root / "log").rglob("*.log"))[:40]
for path in paths:
    if remaining <= 0:
        print("Further extractor diagnostics omitted after the output limit.")
        break
    if path.is_symlink() or not path.is_file():
        continue
    with path.open("rb") as stream:
        if path.suffix == ".log":
            stream.seek(max(0, path.stat().st_size - 65536))
        value = stream.read(65536).decode("utf-8", errors="replace")
    if path.suffix == ".log":
        value = "\n".join(line for line in value.splitlines()
                          if re.search(r"\b(error|warning|fatal)\b|unknown argument", line, re.I))
    if not value:
        continue
    print(f"--- {path.relative_to(root)} ---")
    print(value[:remaining])
    remaining -= len(value)
PY
  exit 0
fi
if [ "$#" -ne 0 ]; then
  echo "Usage: tools/codeql-build-mac.sh [--diagnostics]" >&2
  exit 2
fi

project_root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$project_root"
build_dir="$(mktemp -d "$project_root/.codeql-build.XXXXXX")"
trap 'rm -rf "$build_dir"' EXIT
sdk_path="$(xcrun --sdk macosx --show-sdk-path)"
clang_path="$(xcrun --find clang)"
swift_path="$(xcrun --find swiftc)"
swift_sources=(Mac/Sources/*.swift Mac/Tests/*.swift)

# Fail if a new Swift helper is added without being included in this build.
python3 - "${swift_sources[@]}" Mac/Icon.swift <<'PY'
from pathlib import Path
import sys
included = {Path(path) for path in sys.argv[1:]}
actual = set(Path("Mac").rglob("*.swift"))
if included != actual:
    raise SystemExit("Swift analysis input mismatch: " +
                     ", ".join(str(path) for path in sorted(included ^ actual)))
print(f"Compiling all {len(included)} Swift source files for analysis.")
PY

"$swift_path" --version
echo "Compiling native bridge for Swift analysis."
"$clang_path" -target arm64-apple-macos13 -isysroot "$sdk_path" -O0 \
  -Wall -Wextra -Werror -c Mac/Sources/NativeReader.c -o "$build_dir/NativeReader.o"
echo "Compiling application and tests in one Swift invocation."
# The extractor sees all source files in one module. Read the bridging header
# directly so it does not depend on a PCH generated by a different compiler.
"$swift_path" -swift-version 5 -target arm64-apple-macos13 -sdk "$sdk_path" \
  -Onone -whole-module-optimization -disable-bridging-pch \
  -import-objc-header Mac/Sources/NativeReader.h "${swift_sources[@]}" \
  "$build_dir/NativeReader.o" -framework AppKit -framework PCSC -framework IOKit -framework ImageIO \
  -o "$build_dir/Bricklasaren"
echo "Compiling the icon helper without running it."
"$swift_path" -swift-version 5 -target arm64-apple-macos13 -sdk "$sdk_path" \
  -Onone Mac/Icon.swift -framework AppKit -o "$build_dir/BricklasarenIcon"
echo "Swift analysis build completed; release packaging is handled by the Mac workflow."
